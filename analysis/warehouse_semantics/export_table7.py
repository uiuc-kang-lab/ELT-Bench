#!/usr/bin/env python3
"""Export Table 7 from a complete, strictly aggregated warehouse-semantics report.

Run aggregate_run_set.py without --allow-partial first. This exporter checks cohort
coverage, source-report hashes/context and independently recomputes F membership.
It does not repeat raw attempt validation, execute a model, or query a warehouse.
"""
import argparse
from collections import defaultdict
import csv
import hashlib
import json
from pathlib import Path
import re

from protocol import atomic_json, require, sha256

CATEGORY_LABELS = [
    ('numeric_identifier', 'Numeric identifier text and comparison'),
    ('division_precision', 'Decimal division precision'),
    ('integer_avg', 'Integer averages'),
    ('null_ordering', 'Default NULL ordering'),
    ('time_units', 'Time-difference units'),
    ('trailing_spaces', 'Trailing-space comparison'),
]
WAREHOUSES = [('snowflake', 'Snowflake'), ('databricks', 'Databricks'), ('redshift', 'Redshift')]
CAPTION = ('Table 7: Data models with replay-confirmed output-column errors caused by '
           'warehouse-specific semantics across the 300 runs of Claude Agent (Opus 4.7). '
           'Models may appear in multiple rows.')
NOTE = ('The 300 runs are 100 tasks × 3 warehouses. Each cell counts distinct (task, data model) '
        'memberships for that warehouse and challenge. A recorded replay must reproduce the '
        'evaluated baseline and fix at least one originally failing output column under the '
        'same evaluator; the whole model need not pass. Verified downstream failures are included.')
TRUST_BOUNDARY = ('Input must be generated by a fresh strict aggregate_run_set.py invocation. '
                  'This exporter checks complete coverage, internal membership consistency and '
                  'recorded child-report hashes; it does not independently authenticate a forged '
                  'report or repeat raw attempt, SQL citation or warehouse validation.')
CHILD_FILES = ('summary.json', 'coverage.json', 'sites.json', 'propagated_failures.json',
               'case_listings.json', 'table.csv', 'model_table.csv')
CONTEXT_HASHES = {'runner_sha256': 'run.py', 'protocol_sha256': 'protocol.py',
                  'prompt_sha256': 'prompt.txt', 'taxonomy_sha256': 'taxonomy.json',
                  'schema_sha256': 'single_task.output_schema.json'}


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False)


def integer(value):
    return type(value) is int and value >= 0


def hash_value(value):
    return isinstance(value, str) and re.fullmatch(r'[0-9a-f]{64}', value) is not None


def validate_coverage(coverage, expected_tasks):
    require(coverage['selected_tasks'] == expected_tasks and coverage['accepted_tasks'] == expected_tasks
            and coverage['all_selected_complete'] is True, 'Incomplete task coverage; formal Table 7 requires all selected tasks')
    targets = coverage['targets']
    require(len(targets) == expected_tasks, 'Coverage target count mismatch')
    ids, tasks = set(), set()
    for target in targets:
        require(target['status'] == 'accepted' and target['review_status'] == 'complete',
                'Missing, invalid or incomplete task cannot be exported as zero')
        require(target['target_id'] not in ids and target['task_id'] not in tasks, 'Duplicate coverage task/target')
        require(target['warehouses'] == [w for w, _ in WAREHOUSES], 'Coverage must consistently include all three warehouses')
        ids.add(target['target_id']); tasks.add(target['task_id'])
    return {target['target_id']: target for target in targets}


def replay_proof(record):
    replay = record['replay']
    require(replay['kind'] == 'analyst_replay' and replay['baseline_reproduced'] is True,
            'F requires an analyst replay with reproduced baseline')
    require(replay['corrected_sql'] is not None and replay['result_evidence']
            and replay['fixed_columns'] and all(isinstance(c, str) and c for c in replay['fixed_columns']),
            'F requires saved correction, result citations and fixed output columns')
    # model_pass_after may be false: repairing one entire failed column is enough.
    for ref in [replay['corrected_sql']] + replay['result_evidence']:
        require(isinstance(ref, dict) and isinstance(ref.get('artifact_id'), str)
                and isinstance(ref.get('quote'), str) and bool(ref['quote'].strip())
                and type(ref.get('line_start')) is int and type(ref.get('line_end')) is int
                and 1 <= ref['line_start'] <= ref['line_end'], 'Invalid replay citation shape')


def recompute_failures(sites, propagated, targets):
    """Derive F independently of summary counts, preserving direct and propagated proof."""
    known_categories = {c for c, _ in CATEGORY_LABELS}
    known_warehouses = {w for w, _ in WAREHOUSES}
    direct, downstream, site_index = defaultdict(list), defaultdict(list), {}

    def identity(record):
        target_id = record['target_id']
        require(target_id in targets and record['task_id'] == targets[target_id]['task_id'],
                'Failure/site is outside accepted task coverage')
        require(record['category'] in known_categories and record['warehouse'] in known_warehouses,
                'Unknown category or warehouse in evidence records')
        require(isinstance(record['model_id'], str) and record['model_id'], 'Missing data model identity')
        return (record['category'], record['warehouse'], record['task_id'], record['model_id'])

    for site in sites:
        key = identity(site)
        sid = (site['target_id'], site['site_id'])
        require(sid not in site_index, 'Duplicate source site identity')
        site_index[sid] = site
        require(type(site['failure_attributed']) is bool, 'Failure attribution must be boolean')
        if site['failure_attributed']:
            require(site['inclusion'] == 'counted', 'Uncertain/excluded site cannot establish F')
            replay_proof(site)
            direct[key].append(site)
    seen_propagated = set()
    for failure in propagated:
        key = identity(failure)
        require(key not in seen_propagated, 'Duplicate propagated failure membership')
        seen_propagated.add(key)
        replay_proof(failure)
        source_ids = failure['source_site_ids']
        require(bool(source_ids) and len(set(source_ids)) == len(source_ids), 'Missing/duplicate propagated source IDs')
        for site_id in source_ids:
            source = site_index.get((failure['target_id'], site_id))
            require(source is not None and source['inclusion'] == 'counted'
                    and source['warehouse'] == failure['warehouse'] and source['category'] == failure['category'],
                    'Propagated failure lacks a counted source of the same warehouse/category')
        downstream[key].append(failure)
    return direct, downstream


def load_validated_report(report_dir):
    """Check the saved report boundary; original attempt validation belongs upstream."""
    hashes = {}

    def read(relative, parse=True):
        path = report_dir / relative
        raw = path.read_bytes()
        hashes[str(relative)] = hashlib.sha256(raw).hexdigest()
        return json.loads(raw) if parse else raw

    summary = read('summary.json'); coverage = read('coverage.json'); run_set = read('run_set.json')
    sites = read('sites.json'); propagated = read('propagated_failures.json')
    require(summary.get('schema_version') == 1 and summary.get('analysis_mode') == 'independent_task_analysis'
            and summary.get('aggregation_mode') == 'verified_run_set', 'Table 7 requires a verified run-set report')
    require(summary['coverage'] == coverage and summary['run_set'] == run_set, 'Report coverage/provenance files disagree')
    require(run_set.get('schema_version') == 1 and run_set.get('compatible_semantic_protocol') is True,
            'Run-set semantic protocols were not validated as compatible')
    require(summary['prepared_model_warehouse_count'] == 606 and summary['accepted_model_warehouse_count'] == 606,
            'Formal Table 7 requires all 606 prepared and accepted model-warehouse records')
    targets = validate_coverage(coverage, 100)
    provenance = summary['provenance']
    by_target = {p['target_id']: p for p in provenance}
    require(len(provenance) == 100 and len(by_target) == 100 and set(by_target) == set(targets),
            'Accepted provenance must cover each of the 100 tasks exactly once')
    sources = {s['source_id']: s for s in run_set['sources']}
    require(len(sources) == len(run_set['sources']), 'Duplicate source ID')
    source_targets, verified_sites, verified_propagated = set(), [], []
    verified_models = 0
    settings_by_source = {}
    for source_id, source in sources.items():
        selected = source['selected_target_ids']
        if not selected:
            require(source['status'] == 'no_candidates', 'Unvalidated empty source')
            continue
        require(source['status'] == 'validated' and source['returncode'] == 0,
                'Each selected source must have a complete strict-compatible validation report')
        require(len(set(selected)) == len(selected) and not source_targets.intersection(selected),
                'Overlapping source task selection')
        source_targets.update(selected)
        # Keep report verification portable after copying the complete report tree.
        saved_dir = Path(source['validation_report_dir'])
        require(saved_dir.parent.name == 'source_validation' and re.fullmatch(r'[0-9]+', saved_dir.name),
                'Unexpected source-validation report location')
        directory = Path('source_validation') / saved_dir.name
        expected_hashes = source['verification_files_sha256']
        require(set(expected_hashes) == set(CHILD_FILES), 'Missing child verification file hashes')
        child_data = {}
        for name in CHILD_FILES:
            child_data[name] = read(directory / name, parse=name.endswith('.json'))
            require(hash_value(expected_hashes[name]) and hashes[str(directory / name)] == expected_hashes[name],
                    'Source verification report hash mismatch: ' + str(directory / name))
        child = child_data['summary.json']
        require(child['schema_version'] == 1 and child['analysis_mode'] == 'independent_task_analysis',
                'Wrong source verification report schema/mode')
        require(child['coverage'] == child_data['coverage.json'] == source['coverage'], 'Source coverage records disagree')
        child_targets = validate_coverage(child['coverage'], len(selected))
        require(set(child_targets) == set(selected), 'Source verified a different target set')
        require(integer(child['accepted_model_warehouse_count']), 'Invalid source model denominator')
        verified_models += child['accepted_model_warehouse_count']
        child_provenance = {p['target_id']: p for p in child['provenance']}
        require(len(child_provenance) == len(child['provenance']) == len(selected)
                and set(child_provenance) == set(selected), 'Source provenance coverage mismatch')
        source_settings = {}
        for target_id in selected:
            require(target_id in targets, 'Source contains a task outside global coverage')
            target = targets[target_id]; main_prov = by_target[target_id]
            require(target['source_ids'] == [source_id] and main_prov['source_id'] == source_id
                    and main_prov['source_run_dir'] == source['run_dir'], 'Task source assignment mismatch')
            require({k: v for k, v in target.items() if k != 'source_ids'} == child_targets[target_id],
                    'Global and source task coverage disagree')
            require({k: v for k, v in main_prov.items() if k not in {'source_id', 'source_run_dir'}} == child_provenance[target_id],
                    'Global and source accepted provenance disagree')
            context = main_prov['context']; metadata = context['target_metadata']
            require(metadata['target_id'] == target_id and metadata['task_id'] == target['task_id']
                    and metadata['warehouses'] == [w for w, _ in WAREHOUSES]
                    and metadata['agent'] == 'Claude Opus 4.7', 'Provenance cohort differs from Table 7 caption')
            for field, filename in CONTEXT_HASHES.items():
                require(hash_value(context[field]) and context[field] == source['protocol_hashes'][filename],
                        'Task protocol hash differs from its source snapshot')
            require(all(hash_value(context[k]) for k in ('payload_sha256', 'preparer_sha256', 'request_sha256'))
                    and hash_value(main_prov['output_sha256']), 'Malformed accepted input/output hashes')
            settings = context['model_settings']
            require(isinstance(settings.get('model'), str) and settings['model']
                    and isinstance(settings.get('model_reasoning_effort'), str) and settings['model_reasoning_effort'],
                    'Missing analysis model settings')
            source_settings[canonical(settings)] = settings
        settings_by_source[source_id] = list(source_settings.values())
        verified_sites.extend(child_data['sites.json'])
        verified_propagated.extend(child_data['propagated_failures.json'])
    require(source_targets == set(targets) and verified_models == 606, 'Source verification does not cover the complete 100-task/606-model cohort')
    require(sorted(map(canonical, sites)) == sorted(map(canonical, verified_sites)), 'Combined sites differ from verified source sites')
    require(sorted(map(canonical, propagated)) == sorted(map(canonical, verified_propagated)),
            'Combined propagated failures differ from verified source failures')
    direct, downstream = recompute_failures(sites, propagated, targets)
    rows = {}; memberships = []
    expected_keys = {(c, w) for c, _ in CATEGORY_LABELS for w, _ in WAREHOUSES}
    for row in summary['rows']:
        key = (row['category_id'], row['warehouse'])
        require(key in expected_keys and key not in rows, 'Duplicate/unknown category-warehouse summary row')
        require(len(row['counts']) == 5 and all(integer(n) for n in row['counts']), 'Invalid summary count vector')
        claimed = row['failed_model_sets']
        claimed_set = {(m['task_id'], m['model_id']) for m in claimed}
        require(len(claimed_set) == len(claimed) == row['counts'][4], 'F count does not match unique failed_model_sets')
        actual = {(task, model) for category, warehouse, task, model in set(direct) | set(downstream)
                  if (category, warehouse) == key}
        require(actual == claimed_set, 'F membership differs from counted failure sites plus verified propagation')
        rows[key] = row['counts'][4]
        members = []
        for task, model in sorted(actual):
            full_key = key + (task, model)
            proofs = direct.get(full_key, []) + downstream.get(full_key, [])
            target_id = proofs[0]['target_id']; prov = by_target[target_id]
            members.append(dict(task_id=task, model_id=model, target_id=target_id, source_id=prov['source_id'],
                                accepted_result_path=str(Path(prov['source_run_dir']) / 'accepted_results' / (target_id + '.json')),
                                accepted_output_sha256=prov['output_sha256'],
                                direct_sites=direct.get(full_key, []), propagated_failures=downstream.get(full_key, [])))
        memberships.append(dict(category_id=key[0], warehouse=key[1], failed_models_count=rows[key], failed_models=members))
    require(set(rows) == expected_keys, 'Missing category-warehouse row; missing is never zero')
    memberships.sort(key=lambda r: ([c for c, _ in CATEGORY_LABELS].index(r['category_id']),
                                    [w for w, _ in WAREHOUSES].index(r['warehouse'])))
    require(all(sha256(report_dir / name) == digest for name, digest in hashes.items()), 'Report changed while exporting')
    return dict(rows=rows, memberships=memberships, coverage=coverage, run_set=run_set,
                provenance=provenance, input_files_sha256=hashes, settings_by_source=settings_by_source)


def export(report_dir, output_dir):
    report_dir = Path(report_dir).resolve(); output_dir = Path(output_dir).resolve()
    require(not output_dir.exists() or not any(output_dir.iterdir()), 'Output directory must be new or empty')
    require(output_dir != report_dir and report_dir not in output_dir.parents, 'Export outside the input report directory')
    data = load_validated_report(report_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    table = [[label] + [data['rows'][(category, warehouse)] for warehouse, _ in WAREHOUSES]
             for category, label in CATEGORY_LABELS]
    headers = ['Challenge'] + [label for _, label in WAREHOUSES]
    with (output_dir / 'table7.csv').open('w', newline='') as stream:
        writer = csv.writer(stream); writer.writerow(headers); writer.writerows(table)
    markdown = ['**' + CAPTION + '**', '', '| ' + ' | '.join(headers) + ' |',
                '| --- | ---: | ---: | ---: |']
    markdown.extend('| ' + ' | '.join(map(str, row)) + ' |' for row in table)
    (output_dir / 'table7.md').write_text('\n'.join(markdown) + '\n\n' + NOTE + '\n')
    latex = [r'\begin{table}[t]', r'\centering', r'\caption{' + CAPTION.removeprefix('Table 7: ') + '}',
             r'\label{tab:warehouse_semantic_errors}', r'\begin{tabular}{lrrr}', r'\hline',
             ' & '.join(headers) + r' \\', r'\hline']
    latex.extend(' & '.join(map(str, row)) + r' \\' for row in table)
    latex.extend([r'\hline', r'\end{tabular}', r'\par\smallskip', r'{\footnotesize '
                  + NOTE.replace('×', r'$\times$') + '}', r'\end{table}', ''])
    (output_dir / 'table7.tex').write_text('\n'.join(latex))
    atomic_json(output_dir / 'table7_members.json', dict(schema_version=1, statistic='replay_confirmed_failed_models',
                caption=CAPTION, counting_note=NOTE, rows=data['memberships']))
    atomic_json(output_dir / 'coverage.json', data['coverage'])
    outputs = ['table7.csv', 'table7.md', 'table7.tex', 'table7_members.json', 'coverage.json']
    atomic_json(output_dir / 'table7_provenance.json', dict(schema_version=1, status='validated_for_export',
                caption=CAPTION, statistic='F', analysis_mode='independent_task_analysis', aggregation_mode='verified_run_set',
                source_report_dir=str(report_dir), exporter_sha256=sha256(Path(__file__)),
                input_files_sha256=data['input_files_sha256'], output_files_sha256={name: sha256(output_dir / name) for name in outputs},
                task_count=100, warehouse_run_count=300, accepted_model_warehouse_count=606,
                warehouses=[w for w, _ in WAREHOUSES], coverage=data['coverage'],
                run_set=data['run_set'], source_model_settings=data['settings_by_source'], accepted_provenance=data['provenance'],
                validation_boundary=TRUST_BOUNDARY, new_model_calls=0, new_warehouse_queries=0))
    print(json.dumps(dict(status='exported', output_dir=str(output_dir), tasks=100, warehouse_runs=300,
                         accepted_model_warehouse_count=606, rows=6,
                         files=outputs + ['table7_provenance.json'])))
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--report-dir', type=Path, default=Path(__file__).resolve().parent / 'reports/full_astra_high_c16')
    parser.add_argument('--output-dir', type=Path, default=Path(__file__).resolve().parent / 'reports/table7_full_astra_high_c16')
    args = parser.parse_args(argv)
    return export(args.report_dir, args.output_dir)


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (ValueError, KeyError, OSError, TypeError, IndexError) as exc:
        print(json.dumps(dict(status='table7_export_error', error=str(exc))))
        raise SystemExit(1)
